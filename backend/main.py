@public_router.post("/payment/validate-bulk")
async def validate_members_bulk(payload: BulkValidateRequest):
    if not supabase:
        raise HTTPException(status_code=500, detail="Database not available")

    if payload.member_ids:
        ids = payload.member_ids[: payload.limit]
    else:
        try:
            rows = (
                supabase.table("members")
                .select("id")
                .not_.is_("plan", "null")
                .order("created_at", desc=True)
                .limit(payload.limit)
                .execute()
                .data or []
            )
        except Exception as e:
            logger.error(f"Bulk validation: could not list members: {e}")
            raise HTTPException(status_code=400, detail="Could not list members")
        ids = [r["id"] for r in rows if r.get("id")]

    results = []
    summary = {
        "checked": 0, "active": 0, "dormant": 0, "pending": 0,
        "requires_reconciliation": 0, "not_applicable": 0, "errors": 0,
    }

    for member_id in ids:
        try:
            result = calculate_member_payment_validation(member_id)
        except HTTPException as http_err:
            results.append({"member_id": member_id, "success": False, "error": http_err.detail})
            summary["errors"] += 1
            continue
        except Exception as e:
            logger.error(f"Bulk validation error for {member_id}: {e}")
            results.append({"member_id": member_id, "success": False, "error": str(e)})
            summary["errors"] += 1
            continue

        results.append(result)
        summary["checked"] += 1

        if result.get("validation_status") == "NOT_APPLICABLE":
            summary["not_applicable"] += 1
        elif result.get("validation_status") == "REQUIRES_RECONCILIATION":
            summary["requires_reconciliation"] += 1
        else:
            member_status = (result.get("status") or "").lower()
            if member_status in ("active", "dormant", "pending"):
                summary[member_status] += 1

    return {"success": True, "summary": summary, "results": results}

