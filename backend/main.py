_CALLBACK_ACK = {"ResultCode": 0, "ResultDesc": "Accepted"}


@public_router.post("/payment/callback")
async def payment_callback(request: Request):
    """Safaricom M-Pesa STK callback. Always acknowledges so Safaricom does not retry."""

    client_ip = request.client.host if request.client else None
    if not is_ip_allowed(client_ip):
        logger.warning(f"Rejected M-Pesa callback from disallowed IP: {client_ip}")
        raise HTTPException(status_code=403, detail="Forbidden")

    try:
        data = await request.json()
    except Exception as e:
        logger.error("Payment callback JSON error: %s", e)
        return {"ResultCode": 1, "ResultDesc": "Invalid callback JSON"}

    logger.info("M-Pesa STK callback received: checkout_request_id=%s", ((data.get("Body") or {}).get("stkCallback") or {}).get("CheckoutRequestID"))

    try:
        stk_callback = (data.get("Body") or {}).get("stkCallback") or {}
        checkout_request_id = stk_callback.get("CheckoutRequestID")
        result_desc = stk_callback.get("ResultDesc")

        try:
            result_code = int(stk_callback.get("ResultCode"))
        except (TypeError, ValueError):
            result_code = None

        if not checkout_request_id or result_code is None:
            logger.warning("M-Pesa callback missing CheckoutRequestID or ResultCode")
            return {"ResultCode": 1, "ResultDesc": "Incomplete callback"}

        result = (
            supabase.table("payments").select("*")
            .eq("checkout_request_id", checkout_request_id).limit(1).execute()
        )
        if not result.data:
            logger.warning("Payment not found for callback: %s", checkout_request_id)
            return {"ResultCode": 1, "ResultDesc": "Payment record not found; retry"}

        payment = result.data[0]
        payment_id = payment["id"]

        # Idempotency: don't reactivate, overwrite the receipt or double-count.
        if (
            str(payment.get("payment_status", "")).upper() in {"CONFIRMED", "SUCCESSFUL"}
            and payment.get("mpesa_receipt_number")
        ):
            logger.info(f"Payment already successful: {payment_id}")
            return {"ResultCode": 0, "ResultDesc": "Already processed"}

        mpesa_receipt = None
        callback_amount = None
        callback_phone = None
        transaction_date = None

        for item in (stk_callback.get("CallbackMetadata") or {}).get("Item") or []:
            name = item.get("Name")
            value = item.get("Value")
            if name == "MpesaReceiptNumber":
                mpesa_receipt = str(value) if value is not None else None
            elif name == "Amount":
                callback_amount = value
            elif name == "PhoneNumber":
                callback_phone = str(value) if value is not None else None
            elif name == "TransactionDate":
                transaction_date = value

        # Supabase REST does not interpret "now()" as SQL, so use a Python UTC timestamp.
        now_iso = datetime.now(timezone.utc).isoformat()

        if result_code == 0:
            update_data = {
                "payment_status": "CONFIRMED",
                "status": "completed",
                "result_code": 0,
                "result_desc": result_desc or "Payment successful",
                "mpesa_receipt": mpesa_receipt,
                "mpesa_receipt_number": mpesa_receipt,
                "confirmed_at": now_iso,
                "verified_at": now_iso,
                "counts_toward_membership": True,
                "raw_callback": data,
                "updated_at": now_iso,
            }

            if callback_amount is not None:
                try:
                    update_data["amount"] = float(callback_amount)
                except (TypeError, ValueError):
                    pass

            if callback_phone:
                update_data["phone_number"] = callback_phone
                update_data["phone"] = callback_phone

            if transaction_date:
                update_data["notes"] = f"M-Pesa transaction date: {transaction_date}"

            supabase.table("payments").update(update_data).eq("checkout_request_id", checkout_request_id).execute()
            logger.info(f"M-Pesa payment SUCCESSFUL: {checkout_request_id}, receipt={mpesa_receipt}")

            # The DB trigger has already updated the member's payment totals;
            # this only re-derives status/validation metadata from them.
            member_id = payment.get("member_id")
            if member_id:
                try:
                    calculate_member_payment_validation(member_id)
                except Exception as e:
                    logger.exception(f"Post-payment validation failed for {member_id}: {e}")

            refreshed = supabase.table("payments").select("*").eq("id", payment_id).limit(1).execute()
            payment_for_activation = refreshed.data[0] if refreshed.data else {**payment, **update_data}

            try:
                await activate_registration(payment_for_activation)
            except Exception as e:
                logger.exception(f"Activation error for {payment_id}: {e}")

        else:
            supabase.table("payments").update({
                "payment_status": "FAILED",
                "status": "failed",
                "result_code": result_code,
                "result_desc": result_desc,
                "failure_reason": result_desc,
                "confirmed_at": now_iso,
                "verified_at": now_iso,
                "counts_toward_membership": False,
                "raw_callback": data,
                "updated_at": now_iso,
            }).eq("checkout_request_id", checkout_request_id).execute()

            logger.info(
                f"M-Pesa payment FAILED: {checkout_request_id}, code={result_code}, reason={result_desc}"
            )

        return _CALLBACK_ACK

    except Exception as e:
        logger.exception("Payment callback processing error: %s", e)
        return {"ResultCode": 1, "ResultDesc": "Processing failed; retry"}

