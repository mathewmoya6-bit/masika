def _textsms_configured() -> bool:
    return bool(TEXTSMS_API_KEY and TEXTSMS_PARTNER_ID and TEXTSMS_SHORTCODE)


def _textsms_error_parts(data: dict) -> Tuple[Any, Any]:
    """TextSMS spells the key 'respose-code' in some responses."""
    responses = data.get("responses") or []
    if not responses:
        return None, None
    first = responses[0]
    code = first.get("respose-code", first.get("response-code"))
    desc = first.get("response-description") or first.get("respose-description")
    return code, desc


async def _send_sms(phone: str, message: str, label: str) -> Tuple[bool, str]:
    """Send one SMS via TextSMS. Returns (success, detail). Never raises."""
    if not _textsms_configured():
        logger.warning(f"{label}: TEXTSMS_* env vars not fully configured - skipping send")
        return False, "TextSMS not configured (missing TEXTSMS_API_KEY/PARTNER_ID/SHORTCODE)"

    if not httpx:
        logger.error(f"{label}: httpx not available")
        return False, "httpx not available on server"

    formatted_phone = format_phone_number(phone)
    payload = {
        "apikey": TEXTSMS_API_KEY,
        "partnerID": TEXTSMS_PARTNER_ID,
        "message": message,
        "shortcode": TEXTSMS_SHORTCODE,
        "mobile": formatted_phone,
    }

    try:
        async with httpx.AsyncClient(timeout=20) as client:
            response = await client.post(TEXTSMS_SEND_URL, json=payload)

        if response.status_code != 200:
            logger.error(f"{label}: TextSMS HTTP {response.status_code}: {response.text[:300]}")
            return False, f"TextSMS HTTP {response.status_code}: {response.text[:200]}"

        data = response.json()
        code, desc = _textsms_error_parts(data)
        if code is not None and str(code) in ("200", "0"):
            return True, "sent"

        logger.error(f"{label}: send failed for {formatted_phone}: {data}")
        if code is not None:
            return False, f"TextSMS {code}: {desc}"[:250]
        return False, f"TextSMS HTTP {response.status_code}: {str(data)[:200]}"

    except Exception as e:
        logger.error(f"{label}: send error for {formatted_phone}: {e}")
        return False, f"TextSMS request error: {str(e)[:200]}"


