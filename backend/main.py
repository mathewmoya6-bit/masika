#
# DATABASE NOTES
#   - members.member_number (MSK000001 ...) is generated by PostgreSQL
#     (masika_member_number_seq + generate_masika_member_number() trigger).
#     Python never generates it; it reads it back after the insert.
#   - A trigger on `payments` owns members.months_paid / months_missing /
#     months_short / amount_paid / amount_expected. Python only reads them.
#   - The trigger must compute amount_expected for Wazazi as
#     principal_monthly_premium + parents x parent_monthly_premium.
#   - payment_type enum includes REGISTRATION, MONTHLY, TOPUP, ADDON.
#   - payments.member_id MUST be nullable: Paybill payments whose account
#     number matches no member are saved with member_id = NULL ("Unassigned").

