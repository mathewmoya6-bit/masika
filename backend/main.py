async def activate_registration(payment: dict):
    """Send the payment confirmation SMS and activate the member / chama group."""
    try:
        payment_type = str(payment.get("payment_type") or "").strip().lower()
        member_id = payment.get("member_id")
        chama_group_id = payment.get("chama_group_id")

        if member_id and payment.get("phone"):
            try:
                lookup = supabase.table("members").select("member_number").eq("id", member_id).limit(1).execute()
                member_number = lookup.data[0].get("member_number") if lookup.data else None
                if member_number:
                    await send_payment_confirmation_sms(
                        payment["phone"], str(payment.get("amount", "")), member_number
                    )
            except Exception as e:
                logger.exception(f"Payment SMS failed: {e}")

        if member_id:
            if payment_type != "registration":
                logger.info(f"Payment {payment.get('id')} is {payment_type}; registration activation skipped.")
                return

            supabase.table("members").update({
                "registration_fee_paid": True,
                "member_status": "ACTIVE",
                "updated_at": datetime.now().isoformat(),
            }).eq("id", member_id).execute()
            logger.info(f"Member {member_id} activated successfully")
            return

        if chama_group_id:
            now = datetime.now().isoformat()
            supabase.table("chama_groups").update({
                "status": "ACTIVE",
                "payment_status": "paid",
                "updated_at": now,
            }).eq("id", chama_group_id).execute()

            try:
                supabase.table("chama_members").update({
                    "is_active": True,
                    "updated_at": now,
                }).eq("chama_group_id", chama_group_id).execute()
            except Exception as e:
                logger.warning(f"Chama members activation failed: {e}")

            logger.info(f"Chama group {chama_group_id} activated")

    except Exception as e:
        logger.exception(f"Activation failed for payment {payment.get('id')}: {e}")

