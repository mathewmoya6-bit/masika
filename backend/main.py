def _parse_date(value) -> Optional[date]:
    if not value:
        return None
    if isinstance(value, datetime):
        return value.date()
    if isinstance(value, date):
        return value
    try:
        return datetime.fromisoformat(str(value).replace("Z", "+00:00")).date()
    except Exception:
        try:
            return date.fromisoformat(str(value)[:10])
        except Exception:
            return None


def _months_between(start_date: Optional[date], end_date: Optional[date]) -> int:
    if not start_date or not end_date:
        return 0
    months = (end_date.year * 12 + end_date.month) - (start_date.year * 12 + start_date.month)
    return max(0, months)


def calculate_member_payment_validation(member_id: str) -> dict:
    """
    Derive a member's status (ACTIVE / DORMANT / PENDING) and validation
    metadata from the AUTHORITATIVE payment totals on the `members` row.

    A PostgreSQL trigger on `payments` owns months_paid, months_missing,
    months_short, amount_paid and amount_expected. This function READS them
    and writes ONLY: status, member_status, payment_validation_status,
    payment_validated_at, payment_validation_note, updated_at.
    """
    if not supabase:
        raise HTTPException(status_code=500, detail="Database not available")

    member_result = supabase.table("members").select("*").eq("id", member_id).limit(1).execute()
    if not member_result.data:
        raise HTTPException(status_code=404, detail="Member not found")

    member = member_result.data[0]
    plan = (member.get("plan") or "").strip().lower()

    if plan == "chama":
        return {
            "success": False,
            "validation_status": "NOT_APPLICABLE",
            "message": "Chama members use group payment validation.",
        }

    registration_date = _parse_date(member.get("registration_date"))
    if not registration_date:
        return {
            "success": False,
            "validation_status": "REQUIRES_RECONCILIATION",
            "message": "Member has no valid registration date.",
        }

    monthly_fee = get_plan_monthly_fee(plan)
    if monthly_fee <= 0:
        return {
            "success": False,
            "validation_status": "REQUIRES_RECONCILIATION",
            "message": f"No monthly contribution is configured for plan '{plan}'.",
        }

    # Same filter the DB trigger uses, so both systems agree on what counts.
    payment_result = (
        supabase.table("payments")
        .select("*")
        .eq("member_id", member_id)
        .in_("payment_status", ["CONFIRMED", "SUCCESSFUL"])
        .eq("counts_toward_membership", True)
        .order("payment_date", desc=False)
        .execute()
    )

    registration_paid = 0.0
    monthly_payments = []
    for payment in payment_result.data or []:
        payment_type = (payment.get("payment_type") or "").lower()
        if payment_type == "registration":
            registration_paid += float(payment.get("amount") or 0)
        elif payment_type in ("monthly", "topup", "addon"):
            monthly_payments.append(payment)

    expected_months = _months_between(registration_date, date.today())

    months_paid = int(member.get("months_paid") or 0)
    months_missing = int(member.get("months_missing") or 0)
    months_short = int(member.get("months_short") or 0)
    amount_paid = float(member.get("amount_paid") or 0)
    amount_expected = float(member.get("amount_expected") or 0)

    if expected_months == 0:
        current_status = "ACTIVE"
        validation_status = "VALIDATED"
        note = "No monthly contribution period is currently due."
    elif months_missing == 0 and months_short == 0:
        current_status = "ACTIVE"
        validation_status = "VALIDATED"
        note = "All required monthly contributions are satisfied."
    elif not monthly_payments:
        current_status = "PENDING"
        validation_status = "REQUIRES_RECONCILIATION"
        note = (
            "No completed monthly payments exist in the new system. "
            "Historical payments must be imported or verified before "
            "determining current arrears."
        )
    else:
        current_status = "DORMANT"
        validation_status = "VALIDATED"
        note = f"{months_missing} month(s) missing and {months_short} month(s) short."

    now = datetime.now().isoformat()
    try:
        supabase.table("members").update({
            "status": current_status,
            "member_status": current_status,
            "payment_validation_status": validation_status,
            "payment_validated_at": now,
            "payment_validation_note": note,
            "updated_at": now,
        }).eq("id", member_id).execute()
    except Exception as e:
        logger.error(f"Could not save payment validation for {member_id}: {e}")
        raise HTTPException(status_code=400, detail=f"Could not save payment validation: {str(e)}")

    return {
        "success": True,
        "member_id": member_id,
        "member_number": member.get("member_number"),
        "plan": plan,
        "registration_date": registration_date.isoformat(),
        "monthly_fee": monthly_fee,
        "expected_months": expected_months,
        "months_paid": months_paid,
        "months_missing": months_missing,
        "months_short": months_short,
        "amount_expected": round(amount_expected, 2),
        "amount_paid": round(amount_paid, 2),
        "registration_paid": round(registration_paid, 2),
        "status": current_status,
        "payment_validation_status": validation_status,
        "legacy_status": member.get("legacy_status"),
        "legacy_missing_months": member.get("legacy_missing_months"),
        "note": note,
    }


