def find_member_by_identifier(identifier: str) -> Optional[dict]:
    if not supabase:
        return None
    try:
        for field in ("member_number", "username", "email"):
            result = supabase.table("members").select("*").eq(field, identifier).execute()
            if result.data:
                return result.data[0]
        return None
    except Exception as e:
        logger.error(f"Error finding member: {e}")
        return None


def get_member_safe(member: dict) -> dict:
    return {k: v for k, v in member.items() if k not in ("password_hash", "temp_password")}


def get_coverage_status(member: dict) -> str:
    """'Pending' without a registration date, else 'Waiting' / 'Active' by waiting period."""
    reg_date = member.get("registration_date")
    if not reg_date:
        return "Pending"
    waiting_months = member.get("waiting_period_months") or 4
    reg_date = datetime.fromisoformat(reg_date) if isinstance(reg_date, str) else reg_date
    wait_end = reg_date + timedelta(days=waiting_months * 30)
    return "Active" if datetime.now() >= wait_end else "Waiting"


def build_dependant_row(
    principal_member_id: str,
    first_name: str,
    last_name: str,
    relationship: str,
    date_of_birth: Optional[str],
    phone: Optional[str] = None,
    email: Optional[str] = None,
    gender: Optional[str] = None,
    status_value: str = "ACTIVE",
) -> dict:
    full_name = f"{(first_name or '').strip()} {(last_name or '').strip()}".strip()
    row = {
        "principal_member_id": principal_member_id,
        "full_name": full_name,
        "relationship": (relationship or "").upper(),
        "date_of_birth": date_of_birth,
        "phone": phone,
        "email": email,
        "status": status_value,
        "created_at": datetime.now().isoformat(),
    }
    if gender:
        row["gender"] = gender.upper()
    return row


def read_generated_member_identity(new_member: dict) -> Tuple[str, str]:
    """
    Read the DB-generated member_number from the inserted row and make sure
    username is set (login looks members up by username). Returns
    (member_number, username).
    """
    member_number = new_member.get("member_number")
    if not member_number:
        raise HTTPException(
            status_code=500,
            detail="Member was created but member number was not generated",
        )

    username = new_member.get("username")
    if not username:
        username = member_number
        supabase.table("members").update({"username": username}).eq("id", new_member["id"]).execute()

    return member_number, username

